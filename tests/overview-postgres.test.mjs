// Optional isolated PostgreSQL runtime: PGLITE_MODULE points to @electric-sql/pglite/dist/index.js.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

test('overview migration executes with caller RLS and exact bounded summaries', { skip: !process.env.PGLITE_MODULE }, async () => {
  const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
  const db = new PGlite();
  const uid = n => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
  try {
    await db.exec(`
      create role anon; create role authenticated; create schema auth;
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.user',true),'')::uuid$$;
      create table public.members(id uuid primary key, auth_user_id uuid, user_role text, name text);
      create function public.get_member_id() returns uuid language sql stable security definer as $$select id from public.members where auth_user_id=auth.uid()$$;
      create function public.get_user_role() returns text language sql stable security definer as $$select user_role from public.members where auth_user_id=auth.uid()$$;
      create function public.has_permission(m text,l text default 'can_read') returns boolean language sql stable as $$
        select coalesce(public.get_user_role()='admin' or (l='can_read' and m not in ('crm','engineering') and current_setting('test.deny',true) is distinct from m),false)$$;
      create table projects(id uuid primary key,name text,code text,status text,completion_date date,price numeric);
      create table realizations(id uuid primary key,name text,code text,status text,planned_end_date date,contract_amount numeric);
      create table project_tasks(id uuid primary key,name text,status text,project_id uuid,end_date date,member_id uuid);
      create table planning_plans(id uuid primary key,project_id uuid,realization_id uuid,title text);
      create table planning_items(id uuid primary key,plan_id uuid,legacy_project_task_id uuid,name text,status text,end_date date,member_id uuid,item_type text);
      create table planning_assignments(id uuid primary key,item_id uuid,member_id uuid);
      create table attendance_submissions(id uuid primary key,member_id uuid,status text,total_hours numeric,month_date date,submitted_at timestamptz);
      create table payouts(id uuid primary key,member_id uuid,status text,amount numeric,request_date date);
      create table hourly_payout_requests(id uuid primary key,member_id uuid,status text);
      create table employee_requests(id uuid primary key,member_id uuid,status text);
      create table notifications(id uuid primary key,user_id uuid,is_read boolean);
      create table attendance_plans(id uuid primary key,member_id uuid,date date,cancelled boolean,kind text);
      create table attendance(id uuid primary key,member_id uuid,date date);
      create table engineering_activities(id uuid primary key,project_id uuid,subject text,status text,end_date date);
      create table subjects(id uuid primary key,name text);
      create table crm_opportunities(id uuid primary key,number text,title text,stage text,status text,expected_close_date date,value numeric,probability numeric,subject_id uuid,deleted_at timestamptz,archived_at timestamptz,cancelled_at timestamptz);
      create table crm_commercial_documents(id uuid primary key,type text,total numeric,status text,deleted_at timestamptz,archived_at timestamptz,cancelled_at timestamptz);
      create table commercial_item_catalog(id uuid primary key,is_active boolean,archived_at timestamptz);
      create table documents(id uuid primary key);
      create function list_projects_safe() returns setof projects language sql stable as $$select * from public.projects$$;
      create function list_realizations_safe() returns setof realizations language sql stable security definer as $$select * from public.realizations$$;
      create function get_company_financials() returns table(realized_profit numeric,potential_profit numeric,total_project_value numeric,unallocated_budget numeric) language sql stable as $$select 1::numeric,2::numeric,3::numeric,4::numeric$$;
      create function get_overhead_summary() returns table(total_allocated_overhead numeric,total_accounted_overhead numeric) language sql stable as $$select 5::numeric,6::numeric$$;
      grant usage on schema public,auth to authenticated,anon;
      grant select on all tables in schema public to authenticated;
      revoke select on public.realizations from authenticated;
      grant select (id,name,status,planned_end_date) on public.realizations to authenticated;
      insert into members values ('${uid(1)}','${uid(101)}','admin','Admin'),('${uid(2)}','${uid(102)}','user','Worker'),('${uid(3)}','${uid(103)}','user','Other');
      insert into projects values ('${uid(10)}','Test','PR-26-1','active','2026-10-10',1000),('${uid(11)}','Closed','PR-26-2','closed','2026-01-01',500);
      insert into planning_plans values ('${uid(20)}','${uid(10)}',null,'Test');
      insert into project_tasks values ('${uid(30)}','Legacy open','Nové','${uid(10)}','2026-09-01','${uid(2)}'),('${uid(31)}','Legacy replaced','Nové','${uid(10)}','2026-09-01','${uid(2)}'),('${uid(32)}','Other','Nové','${uid(10)}','2026-09-01','${uid(3)}');
      insert into planning_items values ('${uid(40)}','${uid(20)}','${uid(31)}','Done replaces legacy','done','2026-09-01','${uid(2)}','task'),('${uid(41)}','${uid(20)}',null,'Multiple assignments','ready','2026-10-01','${uid(2)}','task');
      insert into planning_assignments values ('${uid(50)}','${uid(41)}','${uid(2)}'),('${uid(51)}','${uid(41)}','${uid(2)}');
      insert into notifications values ('${uid(60)}','${uid(102)}',false),('${uid(61)}','${uid(103)}',false),('${uid(62)}','${uid(102)}',true);
      insert into attendance_plans values ('${uid(70)}','${uid(2)}','2026-09-30',false,'work');
      insert into payouts values ('${uid(80)}','${uid(3)}','pending',9000,'2026-09-01');
      insert into crm_opportunities(id,number,title,stage,status,value,probability,expected_close_date)
        select gen_random_uuid(),i::text,'OP '||i,'lead','active',100,50,'2026-09-01' from generate_series(1,25) i;
      insert into crm_commercial_documents(id,type,total,status) select gen_random_uuid(),'offer',200,'draft' from generate_series(1,20);
      alter table project_tasks enable row level security;
      create policy own_tasks on project_tasks for select to authenticated using (public.get_user_role()='admin' or member_id=public.get_member_id());
      alter table payouts enable row level security;
      create policy own_payouts on payouts for select to authenticated using (public.get_user_role()='admin' or member_id=public.get_member_id());
      alter table projects enable row level security;
      create policy visible_project on projects for select to authenticated using (public.get_user_role()='admin' or id='${uid(10)}');
    `);
    await db.exec(await readFile(new URL('../supabase/migrations/20260929190000_portal_overview_read_models.sql', import.meta.url), 'utf8'));
    const asUser = async (id, sql) => {
      await db.exec(`reset role; select set_config('test.user','${id ? uid(id) : ''}',false); set role authenticated;`);
      return (await db.query(sql)).rows[0]?.result;
    };
    const work = await asUser(102, "select get_my_work_overview_v2('2026-09-30') as result");
    await assert.rejects(db.query('select contract_amount from public.realizations'), /permission denied/);
    assert.equal(work.openCount, 2, 'legacy replacement and duplicate assignment not counted twice');
    assert.equal(work.overdueCount, 1);
    assert.equal(work.notificationCount, 1);
    assert.equal(work.reminders.length, 1);
    assert.equal(work.approvals.length, 0);
    assert.equal(work.tasks.some(t => t.name === 'Other'), false);
    assert.equal(work.tasks[0].name, 'Legacy open');
    await db.exec("set test.deny='tasks'");
    assert.equal((await asUser(102, "select get_my_work_overview_v2('2026-09-30') as result")).openCount, 0);
    await db.exec("set test.deny=''");
    const company = await asUser(101, "select get_company_dashboard_v2(false,'2026-09-30') as result");
    assert.equal(company.summary.openOpportunityCount, 25);
    assert.equal(company.topOpportunities.length, 10);
    assert.equal(company.upcomingOpportunities.length, 2);
    assert.equal(company.summary.pipelineValue, 2500);
    assert.equal(company.summary.weightedPipeline, 1250);
    assert.equal(company.summary.offerCount, 20);
    assert.equal(company.summary.offersValue, 4000);
    assert.equal(company.summary.projectCount, 2);
    assert.equal(company.summary.activeProjectCount, 1);
    assert.equal(company.summary.pendingApprovals, 1);
    const privateView = await asUser(101, "select get_company_dashboard_v2(true,'2026-09-30') as result");
    assert.equal(privateView.summary.pipelineValue, 0);
    assert.equal(privateView.topOpportunities[0].value, null);
    assert.equal(privateView.payouts[0].amount, null);
    const workerView = await asUser(102, "select get_company_dashboard_v2(false,'2026-09-30') as result");
    assert.equal(workerView.summary.projectCount, 1, 'RLS applies inside invoker function');
    assert.equal(workerView.summary.openOpportunityCount, 0, 'module denial honored');
    assert.equal(workerView.summary.activeProjectsValue, 0);
    assert.equal(workerView.payouts.length, 0);
    await assert.rejects(asUser(102, 'select get_company_dashboard_finance_v2() as result'), /Admin role/);
    await assert.rejects(asUser(null, 'select get_company_dashboard_v2() as result'), /access denied/);
    await db.exec('reset role; set role anon;');
    await assert.rejects(db.query('select get_my_work_overview_v2()'), /permission denied/);
    console.log('PostgreSQL: migration, RLS, private mode, task deduplication, exact aggregates, grants and access denial passed.');
  } finally { await db.close(); }
});
