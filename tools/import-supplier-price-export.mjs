#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const args = parseArgs(process.argv.slice(2));

if (!args.input || !args.supplier || !args.name) {
  console.error(`Usage:
  node tools/import-supplier-price-export.mjs --input <export.csv|json> --supplier <slug> --name <supplier name> [--website <url>] [--out <file.sql>] [--source-name <label>] [--allow-new-products=false]

Expected columns are flexible. Preferred normalized columns:
  supplier_sku, name, description, category, brand, price_czk_without_vat, price_raw, unit, availability, detail_url, image_url, scraped_at, ean, mpn, catalog_sku
`);
  process.exit(1);
}

const inputPath = path.resolve(args.input);
const raw = fs.readFileSync(inputPath, 'utf8').replace(/^\uFEFF/, '');
const rows = loadRows(raw, inputPath).map(normalizeRow).filter((row) => row.supplier_sku && row.name);

if (!rows.length) {
  throw new Error('No usable rows found. Need at least supplier_sku and name columns.');
}

const supplierSlug = args.supplier;
const supplierName = args.name;
const supplierWebsite = args.website || '';
const sourceName = args['source-name'] || `${supplierName} price export`;
const allowNewProducts = String(args['allow-new-products'] ?? 'true').toLowerCase() !== 'false';
const importedAt = new Date().toISOString();
const DEFAULT_SALE_MARGIN_PERCENT = 20;
const DEFAULT_SALE_MARGIN_FACTOR = 1 - (DEFAULT_SALE_MARGIN_PERCENT / 100);
const sourceFile = args.input.replaceAll('\\', '/');
const jsonPayload = JSON.stringify(rows);

const sql = `-- Generated by tools/import-supplier-price-export.mjs
-- Source: ${escapeSql(sourceFile)}
-- Supplier: ${escapeSql(supplierName)} (${escapeSql(supplierSlug)})
-- Rows: ${rows.length}
-- Default sale margin: ${DEFAULT_SALE_MARGIN_PERCENT}%

begin;

insert into public.product_suppliers (slug, name, website_url, is_active, metadata)
values ('${escapeSql(supplierSlug)}', '${escapeSql(supplierName)}', ${nullableSql(supplierWebsite)}, true, jsonb_build_object('source', 'supplier_price_import'))
on conflict (slug) do update
set name = excluded.name,
    website_url = coalesce(excluded.website_url, public.product_suppliers.website_url),
    is_active = true,
    metadata = coalesce(public.product_suppliers.metadata, '{}'::jsonb) || excluded.metadata,
    updated_at = now();

with source_rows as (
  select *
  from jsonb_to_recordset($supplier_rows$${jsonPayload}$supplier_rows$::jsonb) as x(
    supplier_sku text,
    catalog_sku text,
    ean text,
    mpn text,
    name text,
    description text,
    category text,
    brand text,
    unit text,
    price_without_vat numeric,
    price_raw text,
    currency text,
    vat_rate numeric,
    availability_note text,
    supplier_product_url text,
    image_url text,
    scraped_at timestamptz,
    metadata jsonb
  )
),
supplier_row as (
  select id from public.product_suppliers where slug = '${escapeSql(supplierSlug)}'
),
batch_insert as (
  insert into public.product_import_batches (supplier_id, source_slug, source_name, imported_at, item_count, priced_item_count, status, source_file, metadata)
  select supplier_row.id,
         '${escapeSql(supplierSlug)}_price_import',
         '${escapeSql(sourceName)}',
         '${escapeSql(importedAt)}'::timestamptz,
         count(*)::integer,
         count(*) filter (where source_rows.price_without_vat is not null)::integer,
         'completed',
         '${escapeSql(sourceFile)}',
         jsonb_build_object('generated_by', 'tools/import-supplier-price-export.mjs', 'allow_new_products', ${allowNewProducts})
  from supplier_row cross join source_rows
  group by supplier_row.id
  returning id
),
matched_rows as (
  select
    source_rows.*,
    catalog.id as matched_catalog_item_id
  from source_rows
  left join lateral (
    select item.id
    from public.commercial_item_catalog item
    where (source_rows.catalog_sku is not null and lower(item.sku) = lower(source_rows.catalog_sku))
       or (source_rows.catalog_sku is not null and lower(item.code) = lower(source_rows.catalog_sku))
       or (source_rows.supplier_sku is not null and lower(item.sku) = lower(source_rows.supplier_sku))
       or (source_rows.ean is not null and coalesce(item.metadata->>'ean', '') = source_rows.ean)
       or (source_rows.mpn is not null and coalesce(item.metadata->>'mpn', '') = source_rows.mpn)
    order by
      case
        when source_rows.catalog_sku is not null and lower(item.sku) = lower(source_rows.catalog_sku) then 1
        when source_rows.catalog_sku is not null and lower(item.code) = lower(source_rows.catalog_sku) then 2
        when source_rows.supplier_sku is not null and lower(item.sku) = lower(source_rows.supplier_sku) then 3
        when source_rows.ean is not null and coalesce(item.metadata->>'ean', '') = source_rows.ean then 4
        else 5
      end
    limit 1
  ) catalog on true
),
new_catalog as (
  ${allowNewProducts ? `insert into public.commercial_item_catalog (sku, code, name, description, category, unit, product_type, default_unit_price, default_vat_rate, purchase_price, currency, image_url, is_active, source, metadata)
  select supplier_sku,
         supplier_sku,
         name,
         description,
         category,
         coalesce(unit, 'ks'),
         'manufactured',
         case when coalesce(price_without_vat, 0) > 0 then round(coalesce(price_without_vat, 0) / ${DEFAULT_SALE_MARGIN_FACTOR}, 2) else 0 end,
         coalesce(vat_rate, 21),
         coalesce(price_without_vat, 0),
         coalesce(currency, 'CZK'),
         image_url,
         true,
         'import',
         coalesce(metadata, '{}'::jsonb) || jsonb_build_object(
           'supplier', '${escapeSql(supplierName)}',
           'supplier_sku', supplier_sku,
           'supplier_category', category,
           'source_url', supplier_product_url,
           'availability_note', availability_note,
           'price_raw', price_raw,
           'ean', ean,
           'mpn', mpn,
           'brand', brand,
           'scraped_at', scraped_at,
           'default_margin_percent', ${DEFAULT_SALE_MARGIN_PERCENT}
         )
  from matched_rows
  where matched_catalog_item_id is null
    and supplier_sku is not null
    and not exists (
      select 1 from public.commercial_item_catalog existing
      where lower(existing.sku) = lower(matched_rows.supplier_sku)
         or lower(existing.code) = lower(matched_rows.supplier_sku)
    )
  returning id, sku` : `select null::uuid as id, null::text as sku where false`}
),
resolved_rows as (
  select
    matched_rows.*,
    coalesce(matched_rows.matched_catalog_item_id, new_catalog.id) as catalog_item_id
  from matched_rows
  left join new_catalog on lower(new_catalog.sku) = lower(matched_rows.supplier_sku)
),
upserted_offers as (
  insert into public.product_supplier_offers (catalog_item_id, supplier_id, supplier_sku, supplier_product_url, supplier_product_name, supplier_category, availability_note, currency, is_active, last_seen_at, last_price_without_vat, last_price_raw, metadata)
  select resolved_rows.catalog_item_id,
         supplier_row.id,
         resolved_rows.supplier_sku,
         resolved_rows.supplier_product_url,
         resolved_rows.name,
         resolved_rows.category,
         resolved_rows.availability_note,
         coalesce(resolved_rows.currency, 'CZK'),
         true,
         coalesce(resolved_rows.scraped_at, now()),
         resolved_rows.price_without_vat,
         resolved_rows.price_raw,
         coalesce(resolved_rows.metadata, '{}'::jsonb) || jsonb_build_object(
           'brand', resolved_rows.brand,
           'ean', resolved_rows.ean,
           'mpn', resolved_rows.mpn,
           'matching_strategy', case when resolved_rows.matched_catalog_item_id is not null then 'existing_catalog_exact' else 'new_catalog_from_supplier_sku' end
         )
  from resolved_rows cross join supplier_row
  where resolved_rows.catalog_item_id is not null
  on conflict (supplier_id, lower(supplier_sku)) where supplier_sku is not null and supplier_sku <> ''
  do update set catalog_item_id = excluded.catalog_item_id,
                supplier_product_url = excluded.supplier_product_url,
                supplier_product_name = excluded.supplier_product_name,
                supplier_category = excluded.supplier_category,
                availability_note = excluded.availability_note,
                currency = excluded.currency,
                is_active = true,
                last_seen_at = excluded.last_seen_at,
                last_price_without_vat = excluded.last_price_without_vat,
                last_price_raw = excluded.last_price_raw,
                metadata = coalesce(public.product_supplier_offers.metadata, '{}'::jsonb) || excluded.metadata
  returning id, catalog_item_id, supplier_id, supplier_sku
),
snapshot_insert as (
  insert into public.product_supplier_price_snapshots (supplier_offer_id, import_batch_id, scraped_at, price_without_vat, currency, availability_note, price_raw, metadata)
  select offer.id,
         (select id from batch_insert limit 1),
         coalesce(resolved_rows.scraped_at, now()),
         resolved_rows.price_without_vat,
         coalesce(resolved_rows.currency, 'CZK'),
         resolved_rows.availability_note,
         resolved_rows.price_raw,
         coalesce(resolved_rows.metadata, '{}'::jsonb) || jsonb_build_object('source', '${escapeSql(supplierSlug)}_price_import')
  from upserted_offers offer
  join resolved_rows
    on lower(offer.supplier_sku) = lower(resolved_rows.supplier_sku)
  where resolved_rows.catalog_item_id is not null
  on conflict do nothing
  returning supplier_offer_id
)
select
  (select count(*) from source_rows) as input_rows,
  (select count(*) from resolved_rows where catalog_item_id is not null) as resolved_rows,
  (select count(*) from snapshot_insert) as inserted_snapshots;

with affected_catalog as (
  select distinct catalog_item_id
  from public.product_supplier_offers offer
  join public.product_suppliers supplier on supplier.id = offer.supplier_id
  where supplier.slug = '${escapeSql(supplierSlug)}'
)
select public.refresh_product_preferred_supplier(catalog_item_id)
from affected_catalog;

commit;
`;

if (args.out) {
  fs.mkdirSync(path.dirname(path.resolve(args.out)), { recursive: true });
  fs.writeFileSync(path.resolve(args.out), sql, 'utf8');
  console.log(`Wrote ${args.out} (${rows.length} rows).`);
} else {
  process.stdout.write(sql);
}

function parseArgs(argv) {
  const result = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) continue;
    const eq = token.indexOf('=');
    if (eq > -1) {
      result[token.slice(2, eq)] = token.slice(eq + 1);
    } else {
      result[token.slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
    }
  }
  return result;
}

function loadRows(raw, filePath) {
  if (filePath.toLowerCase().endsWith('.json')) {
    const data = JSON.parse(raw);
    return Array.isArray(data) ? data : data.items || data.products || [];
  }
  return parseCsv(raw);
}

function parseCsv(raw) {
  const lines = raw.split(/\r?\n/).filter((line) => line.trim() !== '');
  if (!lines.length) return [];
  const delimiter = detectDelimiter(lines[0]);
  const headers = splitCsvLine(lines[0], delimiter).map((header) => header.trim());
  return lines.slice(1).map((line) => {
    const cells = splitCsvLine(line, delimiter);
    return headers.reduce((row, header, index) => {
      row[header] = cells[index] ?? '';
      return row;
    }, {});
  });
}

function detectDelimiter(line) {
  const semis = (line.match(/;/g) || []).length;
  const commas = (line.match(/,/g) || []).length;
  return semis >= commas ? ';' : ',';
}

function splitCsvLine(line, delimiter) {
  const cells = [];
  let current = '';
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    if (char === '"') {
      if (quoted && line[i + 1] === '"') {
        current += '"';
        i += 1;
      } else {
        quoted = !quoted;
      }
    } else if (char === delimiter && !quoted) {
      cells.push(current);
      current = '';
    } else {
      current += char;
    }
  }
  cells.push(current);
  return cells;
}

function normalizeRow(row) {
  const metadata = parseJson(row.metadata || row.metadata_json || row.properties) || {};
  const supplierSku = pick(row, ['supplier_sku', 'sku', 'code', 'article_number', 'item_number', 'product_code', 'objednaci_cislo', 'objednací_číslo']);
  const price = parseNumber(pick(row, ['price_czk_without_vat', 'price_without_vat', 'purchase_price_without_vat', 'purchase_price', 'net_price', 'netto', 'cena_bez_dph', 'cena']));
  const scrapedAt = pick(row, ['scraped_at', 'imported_at', 'date']) || new Date().toISOString();
  return {
    supplier_sku: clean(supplierSku),
    catalog_sku: clean(pick(row, ['catalog_sku', 'canonical_sku', 'portal_sku'])),
    ean: clean(pick(row, ['ean', 'gtin', 'barcode'])) || clean(metadata.ean),
    mpn: clean(pick(row, ['mpn', 'manufacturer_part_number', 'model'])) || clean(metadata.mpn || metadata.model),
    name: clean(pick(row, ['name', 'title', 'product_name', 'nazev', 'název'])),
    description: clean(pick(row, ['description', 'desc', 'popis'])) || '',
    category: clean(pick(row, ['category', 'supplier_category', 'kategorie'])) || 'Nezarazeno',
    brand: clean(pick(row, ['brand', 'manufacturer', 'vyrobce', 'výrobce'])) || clean(metadata.brand),
    unit: clean(pick(row, ['unit', 'mj', 'jednotka'])) || 'ks',
    price_without_vat: Number.isFinite(price) ? price : null,
    price_raw: clean(pick(row, ['price_raw', 'raw_price', 'cena_raw'])) || clean(metadata.price_raw) || null,
    currency: clean(pick(row, ['currency', 'mena', 'měna'])) || 'CZK',
    vat_rate: parseNumber(pick(row, ['vat_rate', 'dph'])) ?? 21,
    availability_note: clean(pick(row, ['availability', 'availability_note', 'stock', 'dostupnost'])) || clean(metadata.availability_note) || null,
    supplier_product_url: clean(pick(row, ['detail_url', 'source_url', 'url', 'product_url'])) || clean(metadata.source_url) || null,
    image_url: clean(pick(row, ['image_url', 'image', 'img'])) || clean(metadata.image_url) || null,
    scraped_at: scrapedAt,
    metadata: {
      ...metadata,
      source_row: row,
    },
  };
}

function pick(row, keys) {
  const map = Object.fromEntries(Object.entries(row).map(([key, value]) => [normalizeKey(key), value]));
  for (const key of keys) {
    const value = map[normalizeKey(key)];
    if (value !== undefined && value !== null && String(value).trim() !== '') return value;
  }
  return null;
}

function normalizeKey(key) {
  return String(key).trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
}

function clean(value) {
  if (value === undefined || value === null) return null;
  const text = String(value).trim();
  return text === '' ? null : text;
}

function parseNumber(value) {
  if (value === undefined || value === null || value === '') return null;
  if (typeof value === 'number') return value;
  const normalized = String(value)
    .replace(/\s/g, '')
    .replace(/Kč|CZK|EUR|€|\*/gi, '')
    .replace(/,/g, '.');
  const parsed = Number(normalized);
  return Number.isFinite(parsed) ? parsed : null;
}

function parseJson(value) {
  if (!value || typeof value !== 'string') return typeof value === 'object' ? value : null;
  try {
    return JSON.parse(value);
  } catch {
    return null;
  }
}

function escapeSql(value) {
  return String(value ?? '').replace(/'/g, "''");
}

function nullableSql(value) {
  return value ? `'${escapeSql(value)}'` : 'null';
}