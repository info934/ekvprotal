import fs from 'node:fs/promises';
import path from 'node:path';

const GRAPH_ROOT = 'https://graph.microsoft.com/v1.0';
const TARGETS = {
  project: {
    driveId: 'b!ji_dk_YtskGFDtMrktdyLZjyiLiJnQhCqfuIOZBuRQZeVxJ2ecswQaEAvq3Yhwvu',
    rpc: 'list_projects_safe',
  },
  realizace: {
    driveId: 'b!Plxd0G4z30mGyrujAF0m6_XmKoQCCT9PtknhghM5NO2_O2HioRCPTa_LyEkL3-LK',
    rpc: 'list_realizations_safe',
  },
};

const requiredEnvironment = [
  'MS_GRAPH_TENANT_ID',
  'MS_GRAPH_CLIENT_ID',
  'MS_GRAPH_CLIENT_SECRET',
  'PORTAL_TEST_EMAIL',
  'PORTAL_TEST_PASSWORD',
];

const parseArgs = () => {
  const args = process.argv.slice(2);
  const valueAfter = (name) => {
    const index = args.indexOf(name);
    return index >= 0 ? args[index + 1] : null;
  };
  return {
    sqlPath: valueAfter('--output-sql'),
    reportPath: valueAfter('--output-report'),
  };
};

const readEnvFile = async () => {
  const contents = await fs.readFile(path.resolve('.env.local'), 'utf8');
  return Object.fromEntries(contents
    .split(/\r?\n/)
    .filter((line) => line && !line.trimStart().startsWith('#') && line.includes('='))
    .map((line) => {
      const separator = line.indexOf('=');
      return [line.slice(0, separator), line.slice(separator + 1).trim().replace(/^['"]|['"]$/g, '')];
    }));
};

const normalize = (value) => String(value || '')
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toUpperCase()
  .replace(/[^A-Z0-9]+/g, ' ')
  .trim();

const extractCode = (record, entityType) => {
  if (entityType === 'project' && record.code) return String(record.code).trim();
  return String(record.name || '').match(/\b(?:OP|PRO|CT|OBJ)-\d{2}-\d{3}\b/i)?.[0] || '';
};

const codePattern = (code) => {
  const parts = normalize(code).match(/[A-Z]+|\d+/g) || [];
  if (!parts.length) return null;
  return new RegExp(`(^|[^A-Z0-9])${parts.join('[^A-Z0-9]*')}([^A-Z0-9]|$)`, 'i');
};

const fetchJson = async (url, init = {}) => {
  const response = await fetch(url, init);
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload?.error?.message || payload?.message || `${response.status} ${url}`);
  return payload;
};

const getPortalSession = async (supabaseUrl, anonKey) => fetchJson(
  `${supabaseUrl}/auth/v1/token?grant_type=password`,
  {
    method: 'POST',
    headers: { apikey: anonKey, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: process.env.PORTAL_TEST_EMAIL,
      password: process.env.PORTAL_TEST_PASSWORD,
    }),
  },
);

const getGraphToken = async () => {
  const body = new URLSearchParams({
    client_id: process.env.MS_GRAPH_CLIENT_ID,
    client_secret: process.env.MS_GRAPH_CLIENT_SECRET,
    grant_type: 'client_credentials',
    scope: 'https://graph.microsoft.com/.default',
  });
  return fetchJson(
    `https://login.microsoftonline.com/${process.env.MS_GRAPH_TENANT_ID}/oauth2/v2.0/token`,
    { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' }, body },
  );
};

const findMatch = (record, entityType, folders) => {
  const code = extractCode(record, entityType);
  const recordName = normalize(record.name);
  let candidates = [];

  if (code) {
    const pattern = codePattern(code);
    candidates = folders.filter((folder) => pattern.test(normalize(folder.name)));
    if (candidates.length > 1) {
      const exactName = candidates.filter((folder) => normalize(folder.name) === recordName);
      if (exactName.length === 1) candidates = exactName;
    }
  }

  if (!candidates.length && recordName) {
    candidates = folders.filter((folder) => normalize(folder.name) === recordName);
  }

  if (candidates.length === 1) {
    return { status: 'matched', code, folder: candidates[0], method: code ? 'exact_code' : 'exact_name' };
  }
  return {
    status: candidates.length ? 'ambiguous' : 'unmatched',
    code,
    candidates: candidates.map((folder) => folder.name),
  };
};

const sqlLiteral = (value) => `'${String(value ?? '').replaceAll("'", "''")}'`;

const buildSql = (matches) => {
  const values = matches.map(({ entityType, record, match }) => `    (
      v_connection_id,
      ${sqlLiteral(entityType)},
      ${sqlLiteral(record.id)}::uuid,
      ${sqlLiteral(match.folder.name)},
      ${sqlLiteral(match.folder.id)},
      ${sqlLiteral(match.folder.webUrl)},
      'created',
      jsonb_build_object(
        'backfilled', true,
        'legacyFolder', true,
        'matchedBy', ${sqlLiteral(match.method)},
        'recordCode', ${sqlLiteral(match.code)},
        'source', 'sharepoint-root-folder-backfill-2026-07-13'
      )
    )`).join(',\n');

  return `-- One-time linkage of existing portal records to pre-existing SharePoint root folders.
-- Generated by tools/discover-sharepoint-folder-links.mjs using exact code/name matching only.
-- Existing mappings are intentionally preserved.

DO $$
DECLARE
  v_connection_id uuid;
BEGIN
  SELECT id
  INTO v_connection_id
  FROM public.document_storage_connections
  WHERE provider = 'sharepoint'
    AND status = 'active'
  ORDER BY is_default DESC, created_at ASC
  LIMIT 1;

  IF v_connection_id IS NULL THEN
    RAISE EXCEPTION 'Active SharePoint storage connection was not found';
  END IF;

  INSERT INTO public.document_storage_folders (
    connection_id,
    entity_type,
    entity_id,
    folder_path,
    external_folder_id,
    external_web_url,
    status,
    metadata
  )
  VALUES
${values}
  ON CONFLICT (connection_id, entity_type, entity_id) DO NOTHING;
END $$;
`;
};

const main = async () => {
  const missing = requiredEnvironment.filter((name) => !process.env[name]);
  if (missing.length) throw new Error(`Missing environment variables: ${missing.join(', ')}`);

  const args = parseArgs();
  const localEnv = await readEnvFile();
  const supabaseUrl = localEnv.VITE_SUPABASE_URL;
  const anonKey = localEnv.VITE_SUPABASE_ANON_KEY;
  if (!supabaseUrl || !anonKey) throw new Error('VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY is missing.');

  const [session, graphSession] = await Promise.all([
    getPortalSession(supabaseUrl, anonKey),
    getGraphToken(),
  ]);
  const portalHeaders = {
    apikey: anonKey,
    Authorization: `Bearer ${session.access_token}`,
    'Content-Type': 'application/json',
  };
  const graphHeaders = { Authorization: `Bearer ${graphSession.access_token}` };

  const matches = [];
  const report = { generatedAt: new Date().toISOString(), targets: {} };
  for (const [entityType, target] of Object.entries(TARGETS)) {
    const [records, folderPayload] = await Promise.all([
      fetchJson(`${supabaseUrl}/rest/v1/rpc/${target.rpc}`, {
        method: 'POST', headers: portalHeaders, body: '{}',
      }),
      fetchJson(`${GRAPH_ROOT}/drives/${encodeURIComponent(target.driveId)}/root/children?$select=id,name,webUrl,folder&$top=999`, {
        headers: graphHeaders,
      }),
    ]);
    const folders = (folderPayload.value || []).filter((item) => item.folder && item.name !== 'EKVPortal');
    const results = records.map((record) => ({ record, match: findMatch(record, entityType, folders) }));
    for (const result of results.filter((item) => item.match.status === 'matched')) {
      matches.push({ entityType, ...result });
    }
    report.targets[entityType] = {
      recordCount: records.length,
      legacyRootFolderCount: folders.length,
      matched: results.filter((item) => item.match.status === 'matched').map((item) => ({
        id: item.record.id,
        code: item.match.code || null,
        name: item.record.name,
        folderName: item.match.folder.name,
        folderId: item.match.folder.id,
        webUrl: item.match.folder.webUrl,
        method: item.match.method,
      })),
      ambiguous: results.filter((item) => item.match.status === 'ambiguous').map((item) => ({
        id: item.record.id, code: item.match.code || null, name: item.record.name, candidates: item.match.candidates,
      })),
      unmatched: results.filter((item) => item.match.status === 'unmatched').map((item) => ({
        id: item.record.id, code: item.match.code || null, name: item.record.name,
      })),
    };
  }

  if (args.sqlPath) await fs.writeFile(path.resolve(args.sqlPath), buildSql(matches), 'utf8');
  if (args.reportPath) await fs.writeFile(path.resolve(args.reportPath), `${JSON.stringify(report, null, 2)}\n`, 'utf8');

  for (const [entityType, targetReport] of Object.entries(report.targets)) {
    console.log(`${entityType}: records=${targetReport.recordCount}, matched=${targetReport.matched.length}, ambiguous=${targetReport.ambiguous.length}, unmatched=${targetReport.unmatched.length}`);
  }
  console.log(`Generated mappings: ${matches.length}`);
};

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
